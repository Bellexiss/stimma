	<ul class="care-dots-list">
		<li>Куртки з шкірозамінника дуже практичні. Якщо на ній є забруднення, то їх можна видалити змоченою в воді губкою. Деякі куртки з шкірозамінника можна прати у делікатному режимі в пральній машині.</li>
		<li>Поліестерові куртки є найменш примхливими в догляді. Їх можна чистити щіткою або прати в машині при температурі близько 30 градусів у делікатному режимі. Куртки з поліестеру швидко сохнуть і довго зберігають свою форму на відміну від виробів з натуральних матеріалів.</li>
