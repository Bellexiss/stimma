		 Як доглядати за куртками з різних матеріалів?
	</div>
	<p>
		 Для правильного очищення верхнього одягу потрібно спочатку дізнатися про склад тканини і вид наповнювача. Найчастіше куртки і пальто виготовляються з поліестеру, шкірозамінника. Наповнювачем в основному служать синтетичний пух і слімтекс.
