	<div class="care-shortcuts-group-title">
		 Верхній одяг
	</div>
	<div class="care-shortcuts-group-semi-title">
		 (пальто, блейзери, жакети)
	</div>
	<p>
		 Дотримання необхідних вимог щодо очищення верхнього одягу допоможе зберегти його в належному стані на тривалий час. Тому важливо дотримуватися основних правил догляду за верхнім одягом:
	</p>
	<p>
	</p>
	<ul class="care-dots-list">
		<li>рекомендована професійна хімчистка;</li>
		<li>не прати;</li>
		<li>не відбілювати;</li>
		<li>прасувати при низькій температурі;</li>
		<li>зберігати на плічках.</li>
	</ul>
	<div class="care-shortcuts-group-semi-title">
		 (шуби/вироби з хутра)
	</div>
	<p>
		 Дотримання необхідних вимог щодо очищення виробів з хутра допоможе зберегти його в належному стані на тривалий час. Тому важливо дотримуватися основних правил догляду за верхнім одягом:
	</p>
	<p>
	</p>
	<ul class="care-dots-list">
		<li>Чистка: не періть удома. Для серйозного чищення — лише професійна хімчистка, яка спеціалізується на хутрі.</li>
		<li>Вологість: якщо шуба намокла (сніг, дощ), струсіть її й дайте висохнути природно при кімнатній температурі. Не використовуйте фен чи обігрівач.</li>
		<li>Зберігання: тримайте шубу на широких плічках, у дихаючому чохлі (не в поліетилені), подалі від сонця та батарей.</li>
		<li>Провітрювання: час від часу провітрюйте шубу в прохолодному місці без протягів.</li>
		<li>Захист від молі: використовуйте спеціальні засоби (лаванда, кедр), але не торкайтеся ними безпосередньо хутра.</li>
		<li>Не носіть важкі сумки на плечі — це може зіпсувати ворс і мездру.</li>
	</ul>
