    <div class="care-block-title">
        Как ухаживать за куртками из разных материалов?
    </div>
    <p>Для правильной очистки верхней одежды нужно сначала узнать состав ткани и вид наполнителя. Чаще всего куртки и пальто изготавливаются из полиэстера, кожзама. Наполнителем в основном служат синтетический пух и слимтекс.</p>
    <ul class="care-dots-list">
        <li>Куртки из кожзама очень практичны. Если на ней загрязнение, то их можно удалить смоченной в воде губкой. Некоторые куртки из кожзама можно стирать в деликатном режиме в стиральной машине.</li>
        <li>Полиэстеровые куртки наименее капризны в уходе. Их можно чистить щеткой или стирать в машине при температуре около 30 градусов в щекотливом режиме. Куртки из полиэстера быстро сохнут и долго сохраняют свою форму в отличие от изделий из натуральных материалов.</li>
    </ul>
