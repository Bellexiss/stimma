				 STIMMA - украинский бренд одежды для женщин и о женщинах.<br>
			</p>
			<p>
				 Адаптируя модные тренды к реальной жизни, наша команда создает современный городской гардероб, доступный женщинам из всех городов Украины, независимо от уровня доходов, типа фигуры и взглядов на жизнь.<br>
			</p>
			<p>
				 Коллекции STIMMA всегда посвящены женской силе, характеру и изобретательности. Создавая для украинских женщин пространство для экспериментов, для нас важно, чтобы все вещи сочетались между собой и формировались в капсулу для разных случаев жизни, а каждый новый дроп был логичным продолжением предыдущего.<br>
			</p>
			<p>
				 Имея сеть магазинов по Украине и регулярно обновляя коллекции, мы делаем ставку на повседневные силуэты, непринужденную цветовую гамму и любовь к деталям.<br>
			</p>
			<p>
				 Бренд был основан в 2010 году.
